# String manipulation
#

movie = "The Lord of the Rings: The Return of the King"

# print number of characters
print('Number of characters: ', len(movie))

# print title in capital letters
print('Title in capital letters: ', capitalize(movie))

# print title in small letters
print('Title in smallletters: ', casefold(movie))

# print how many times the vowel "e" appears in the title
print('The Vovel "e" appears in the title: ', count("e") )

# print where in the text is the word "Lord"
print('The word "Lord is in: ', find("Lord"))

# print where in the text is the word "dragon"
print('The word "dragon is in: ', find("dragon"))